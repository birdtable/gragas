package main

import (
	"fmt"
	"io/fs"
	"os"
	"path"
	"regexp"
	"strings"
)

// The "Where things are" table of AGENTS.md is written from the front matter
// of the hand-written documents: a page that says what it is for in a `for:`
// line is a row, so a pull request that adds a page adds its row with the page
// and touches no line of AGENTS.md. The two generated pages carry no `for:` of
// their own and are written by hand in this file, below.

const (
	agentsFile = "AGENTS.md"
	docsDir    = "docs"
	whereOpen  = "<!-- >>> generated by gragas-docs from the type: and for: of docs/**/*.md: edit those, not this block -->"
	whereClose = "<!-- <<< generated by gragas-docs from the type: and for: of docs/**/*.md -->"
)

// whereRow is one row: what a reader needs, and the cell that names the page that answers it.
type whereRow struct{ Need, Path string }

// generatedRows are the rows of the pages that a generator writes. They have
// no front matter of their own to edit, and layers.md is rendered by a judge
// path this table does not touch, so each row is written by hand here.
func generatedRows() []whereRow {
	return []whereRow{
		{"The commands, their contexts and closing words", "`docs/commands.md`"},
		{"Which package may import which", "`docs/layers.md`, from `layers.yaml`"},
	}
}

// readWhere are the rows of the pages under docs/ whose front matter has a
// `for:`, in the order the folder is walked (by name, folders among them), then the rows of the generated pages. A page with a
// `for:` and no `type:` is an error, not a row. The pages are walked and
// read inside tree, so no link among them leads a read out of it.
func readWhere(tree *os.Root) ([]whereRow, error) {
	var rows []whereRow
	pages := tree.FS()
	err := fs.WalkDir(pages, docsDir, func(rel string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() || path.Ext(rel) != ".md" {
			return err
		}
		data, err := fs.ReadFile(pages, rel)
		if err != nil {
			return err
		}
		meta, _, ok := frontMatter(string(data))
		if !ok || meta["for"] == "" {
			return nil
		}
		if meta["type"] == "" {
			return fmt.Errorf("%s: a page with a for line needs a type", rel)
		}
		rows = append(rows, whereRow{meta["for"], "`" + rel + "`"})
		return nil
	})
	if err != nil {
		return nil, err
	}
	return append(rows, generatedRows()...), nil
}

// renderWhereBlock is the marked block: the table, under its markers.
func renderWhereBlock(rows []whereRow) string {
	lines := make([]string, len(rows))
	for i, r := range rows {
		lines[i] = "| " + r.Need + " | " + r.Path + " |"
	}
	return markedTable(whereOpen, whereClose, "| You need | Read |\n|---|---|", lines)
}

// whereDocuments is AGENTS.md with its table written from the pages.
func whereDocuments(tree *os.Root) (map[string][]byte, error) {
	rows, err := readWhere(tree)
	if err != nil {
		return nil, err
	}
	text, err := tree.ReadFile(agentsFile)
	if err != nil {
		return nil, err
	}
	out, err := replaceBlock(agentsFile, string(text), whereOpen, whereClose, renderWhereBlock(rows))
	if err != nil {
		return nil, err
	}
	return map[string][]byte{agentsFile: []byte(out)}, nil
}

var frontRe = regexp.MustCompile(`^([a-z-]+): ?(.*)$`)

// frontMatter is the key and value lines between the first two --- lines, and
// the text after them.
func frontMatter(text string) (map[string]string, string, bool) {
	rest, ok := strings.CutPrefix(text, "---\n")
	if !ok {
		return nil, "", false
	}
	head, body, ok := strings.Cut(rest, "\n---\n")
	if !ok {
		return nil, "", false
	}
	meta := map[string]string{}
	for l := range strings.SplitSeq(head, "\n") {
		if m := frontRe.FindStringSubmatch(l); m != nil {
			meta[m[1]] = m[2]
		}
	}
	return meta, body, true
}
