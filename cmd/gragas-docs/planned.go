package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/birdtable/gragas/internal/ordered"
)

// The packages that layers.yaml plans are listed in section 3.3 of the
// architecture by a table written from its planned: list, so a pull request
// that creates a package moves one line of layers.yaml and touches no line of
// the architecture. The rows of the hand-written table above it are paths that
// are not packages of this repository.

const (
	plannedOpen  = "<!-- >>> generated by gragas-docs from layers.yaml: planned packages -->"
	plannedClose = "<!-- <<< generated by gragas-docs from layers.yaml: planned packages -->"
	layersFile   = "layers.yaml"
	archFile     = "docs/architecture.md"
)

// plannedDocuments is the architecture with its planned-packages block
// written, by path, read through tree.
func plannedDocuments(tree *os.Root) (map[string][]byte, error) {
	arch, err := tree.ReadFile(filepath.FromSlash(archFile))
	if err != nil {
		return nil, err
	}
	planned, err := readPlanned(tree)
	if err != nil {
		return nil, err
	}
	text, err := replaceBlock(archFile, string(arch), plannedOpen, plannedClose, renderPlannedBlock(planned))
	if err != nil {
		return nil, err
	}
	return map[string][]byte{archFile: []byte(text)}, nil
}

// plannedPackage is a package layers.yaml plans, with the milestone that creates it.
type plannedPackage struct{ Path, Milestone string }

// readPlanned are the packages of the planned: list, in its order, read
// through tree.
func readPlanned(tree *os.Root) ([]plannedPackage, error) {
	data, err := tree.ReadFile(layersFile)
	if err != nil {
		return nil, err
	}
	doc, err := ordered.ParseYAML(data)
	if err != nil {
		return nil, fmt.Errorf("%s: %w", layersFile, err)
	}
	m, ok := doc.(*ordered.Map)
	if !ok {
		return nil, fmt.Errorf("%s: not a map", layersFile)
	}
	var out []plannedPackage
	for _, e := range ordered.Maps(m.List("planned")) {
		for _, p := range ordered.Strings(e.List("packages")) {
			out = append(out, plannedPackage{p, e.Str("created")})
		}
	}
	return out, nil
}

// renderPlannedBlock is the marked block: the table of the planned packages.
func renderPlannedBlock(ps []plannedPackage) string {
	rows := make([]string, len(ps))
	for i, p := range ps {
		rows[i] = fmt.Sprintf("| `%s` | this repository | created in %s |", p.Path, p.Milestone)
	}
	return markedTable(plannedOpen, plannedClose, "| Path | Whose | Created in |\n|---|---|---|", rows)
}

// markedTable is a table between its open and close markers: the head, then
// one row a line.
func markedTable(open, closing, head string, rows []string) string {
	var b strings.Builder
	b.WriteString(open + "\n\n" + head + "\n")
	for _, r := range rows {
		b.WriteString(r + "\n")
	}
	b.WriteString("\n" + closing + "\n")
	return b.String()
}

// replaceBlock is text with what lies from open to close, both lines included,
// replaced by block. name is the file, for the error.
func replaceBlock(name, text, open, close, block string) (string, error) {
	i, j := strings.Index(text, open), strings.Index(text, close)
	if i < 0 || j < i {
		return "", fmt.Errorf("%s has no block marked %q", name, open)
	}
	return text[:i] + block + strings.TrimPrefix(text[j+len(close):], "\n"), nil
}
