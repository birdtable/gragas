package internal

import (
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"testing"
)

// wholeTreeWalk is a walk of the repository root or of a folder a test names
// dir, which can reach explorer/.
var wholeTreeWalk = regexp.MustCompile(`filepath\.Walk(Dir)?\((root|dir)\b|fs\.WalkDir\(\w+, "\."`)

// walkersWithoutNodeModules is every test file under dir that walks a whole
// tree and never names node_modules. explorer-test rewrites explorer/node_modules
// on each run, and Go's test cache hashes every folder a test opens, so a walk
// that reads it makes the package miss the cache on the next run.
func walkersWithoutNodeModules(t *testing.T, dir string) []string {
	t.Helper()
	files, err := filepath.Glob(filepath.Join(dir, "*_test.go"))
	if err != nil {
		t.Fatal(err)
	}
	var found []string
	for _, f := range files {
		// Its walks are Go source inside strings, the plants a linter reads.
		if filepath.Base(f) == "preset_gosec_plants_test.go" {
			continue
		}
		src, err := os.ReadFile(f)
		if err != nil {
			t.Fatal(err)
		}
		text := string(src)
		if wholeTreeWalk.MatchString(text) && !strings.Contains(text, `"node_modules"`) {
			found = append(found, f)
		}
	}
	return found
}

func TestNoTreeWalkOfTheTestsReadsNodeModules(t *testing.T) {
	t.Parallel()
	// internal/repo/* are the checks split from internal by what they read (gragas#1194).
	dirs := []string{filepath.Join(root, "internal"), filepath.Join(root, "internal", "cli", "root")}
	for _, group := range []string{"docs", "explorer", "gocode", "rulebook"} {
		dirs = append(dirs, filepath.Join(root, "internal", "repo", group))
	}
	for _, dir := range dirs {
		if found := walkersWithoutNodeModules(t, dir); len(found) != 0 {
			t.Errorf("these tests walk a whole tree and do not skip node_modules, which breaks Go's test cache: %q", found)
		}
	}
	dir := t.TempDir()
	planted := "package p\n\nfunc f() { _ = filepath.WalkDir(root, nil) }\n"
	if err := os.WriteFile(filepath.Join(dir, "planted_test.go"), []byte(planted), 0o600); err != nil {
		t.Fatal(err)
	}
	if found := walkersWithoutNodeModules(t, dir); len(found) != 1 {
		t.Errorf("the planted walk found %q, want its file", found)
	}
}
