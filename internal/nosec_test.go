// gosec reads its own suppression comments, revive its own directives, and
// golangci-lint drops every finding in a file it reads as generated;
// suppressions.txt counts none of them. So .golangci.yml sets gosec to read no
// such comment and the lint to read no generated-file header (cli.process.1,
// gates.exemptions.1; gragas#397), and contexts_test.go runs that very file
// over planted modules. revive has no setting that reads no directive, so
// only the tree check holds it. A suppression is a nolint with its reason.
// These tests hold every Go file of the tree to holding no such comment,
// directive or header at all, so the tree stays clean even if a setting is
// lost.

// silencers are the comments that silence a finding outside suppressions.txt:
// gosec's suppression comments, revive's directives (disable, disable-line,
// disable-next-line, each with or without a rule, and the enable that ends
// one), and the markers golangci-lint's lax mode reads as a generated file.
// Each is built here, in lower case, so this file holds none of them.
func silencers() []string {
	return []string{
		"#" + "nosec",
		"gosec" + ":disable",
		"revive" + ":disable",
		"revive" + ":enable",
		"code " + "generated",
		"do not " + "edit",
		"autogenerated " + "file",
		"* generated by: " + "swagger codegen ",
	}
}

// silencedLines is each line of a Go file in fsys that holds a silencer, as
// "<path>:<line>", and how many Go files it read. It walks every folder the
// go tool builds from, so it skips those starting with "." or "_", as the go
// tool does.
func silencedLines(fsys fs.FS) ([]string, int, error) {
	var out []string
	var read int
	err := fs.WalkDir(fsys, ".", func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			if p != "." && (strings.HasPrefix(d.Name(), ".") || strings.HasPrefix(d.Name(), "_") || d.Name() == "node_modules") {
				return fs.SkipDir
			}
			return nil
		}
		if !strings.HasSuffix(p, ".go") {
			return nil
		}
		data, err := fs.ReadFile(fsys, p)
		if err != nil {
			return err
		}
		read++
		for i, l := range strings.Split(strings.ToLower(string(data)), "\n") {
			if slices.ContainsFunc(silencers(), func(m string) bool { return strings.Contains(l, m) }) {
				out = append(out, fmt.Sprintf("%s:%d", p, i+1))
			}
		}
		return nil
	})
	return out, read, err
}

// TestNoGoFileHoldsASilencer: the tree holds no gosec suppression comment,
// no revive directive and no generated-file header; a finding is fixed, or is
// a nolint with its reason, listed in suppressions.txt.
func TestNoGoFileHoldsASilencer(t *testing.T) {
	t.Parallel()
	found, read, err := silencedLines(os.DirFS(root))
	if err != nil {
		t.Fatal(err)
	}
	if read < 100 {
		t.Fatalf("the walk read %d Go files, so it is not reading the tree", read)
	}
	for _, f := range found {
		t.Errorf("%s: a gosec suppression comment, a revive directive or a generated-file header silences a finding outside suppressions.txt; fix it, or use a nolint with its reason and list it there", f)
	}
}

// TestAPlantedSilencerFailsTheTreeCheck: each silencer, in a line or a block
// comment and in any case, in any folder the go tool builds from, is found; the
// bare words, a listed nolint and a folder the go tool skips are not.
func TestAPlantedSilencerFailsTheTreeCheck(t *testing.T) {
	t.Parallel()
	// spelled again, so a narrowed silencers shows
	nosec, disable := "#"+"nosec", "gosec"+":disable"
	header := "// Code " + "generated by hand. DO NOT " + "EDIT."
	revive := "revive" + ":"
	fsys := fstest.MapFS{
		"internal/run/a.go":          {Data: []byte("package run\n\nvar _ = 1 // " + nosec + " G204\n")},
		"internal/run/b_test.go":     {Data: []byte("package run\n\n/* " + strings.ToUpper(nosec) + " */\n")},
		"cmd/tool/main.go":           {Data: []byte("package main\n\n//" + disable + " G204\nfunc main() {}\n")},
		"internal/run/testdata/x.go": {Data: []byte("package x // " + nosec + "\n")},
		"internal/gen/a.go":          {Data: []byte(header + "\n\npackage gen\n")},
		"internal/gen/b_test.go":     {Data: []byte("// Code " + "generated by a tool.\n\npackage gen\n")},
		"internal/gen/c.go":          {Data: []byte("// DO NOT " + "EDIT this file.\n\npackage gen\n")},
		"internal/gen/d.go":          {Data: []byte("// This is an AUTOGENERATED " + "FILE.\n\npackage gen\n")},
		"internal/gen/e.go":          {Data: []byte("/*\n * Generated by: " + "Swagger Codegen (x)\n */\n\npackage gen\n")},
		"internal/rev/a.go":          {Data: []byte("//" + revive + "disable\npackage rev\n")},
		"internal/rev/b.go":          {Data: []byte("package rev\n\nvar myUrl = 1 //" + revive + "disable-line:var-naming\n")},
		"internal/rev/c_test.go":     {Data: []byte("package rev\n\n// " + strings.ToUpper(revive) + "DISABLE-NEXT-LINE\nvar myUri = 2\n")},
		"internal/rev/d.go":          {Data: []byte("package rev\n\n/* " + revive + "enable:exported */\n")},
		"internal/run/clean.go":      {Data: []byte("package run\n\nvar _ = 2 //nolint:gosec // a listed reason\n\n// nosec is a word here, revive runs, and the rows are generated by gragas gen.\n")},
		".tools/x.go":                {Data: []byte("package x // " + nosec + "\n")},
		"_old/x.go":                  {Data: []byte(header + "\n\npackage x\n")},
		"internal/run/notes.txt":     {Data: []byte(nosec + "\n" + header + "\n")},
	}
	got, read, err := silencedLines(fsys)
	if err != nil || read != 14 {
		t.Fatalf("read %d Go files, want 14: %v", read, err)
	}
	want := []string{
		"cmd/tool/main.go:3",
		"internal/gen/a.go:1", "internal/gen/b_test.go:1", "internal/gen/c.go:1", "internal/gen/d.go:1", "internal/gen/e.go:2",
		"internal/rev/a.go:1", "internal/rev/b.go:3", "internal/rev/c_test.go:3", "internal/rev/d.go:3",
		"internal/run/a.go:3", "internal/run/b_test.go:3", "internal/run/testdata/x.go:1",
	}
	if !slices.Equal(got, want) {
		t.Errorf("found %q, want %q", got, want)
	}
}
