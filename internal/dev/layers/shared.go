// The shared registry is one row a capability that more than one package or
// program needs: the package that owns it and the export to use, the shared
// module's package and export where it has one, the primitives the owner
// alone may reach, and whether the lint holds them yet. task gen renders the
// bans of each row that is not later into the lint file, and the rows into
// the instruction block of AGENTS.md (arch.shared.8).
const (
	SharedFile   = "gate/shared.yaml"
	SharedSchema = "shared"
	SharedRule   = "arch.shared.8"
	AgentsFile   = "AGENTS.md"
)

// The statuses of a row: its owner is gragas's own code, or a wrapper of a
// shared module's export; or the ban is not rendered yet, since copies of
// the primitive stand outside the owner.
const (
	StatusLocal  = "local"
	StatusShared = "shared"
	StatusLater  = "later"
)

// SharedModules are the shared modules gragas imports, the platform's
// libraries: a row's shared package is a package of one of them.
func SharedModules() []string {
	return []string{"github.com/birdtable/go-console", "github.com/birdtable/go-files", "github.com/birdtable/go-run"}
}

// SharedModuleOf is the shared module pkg is a package of, "" when none.
func SharedModuleOf(pkg string) string {
	for _, m := range SharedModules() {
		if pkg == m || strings.HasPrefix(pkg, m+"/") {
			return m
		}
	}
	return ""
}

// The markers of the shared blocks in the lint file: the forbidigo rows of
// the calls, the depguard rules of the imports, and the exclusion that lets
// each owner make its own calls.
const (
	CallsBeginMark   = "# >>> generated by gragas gen from gate/shared.yaml: the shared primitives' calls"
	CallsEndMark     = "# <<< generated by gragas gen: the shared primitives' calls"
	ImportsBeginMark = "# >>> generated by gragas gen from gate/shared.yaml: the shared primitives' imports"
	ImportsEndMark   = "# <<< generated by gragas gen: the shared primitives' imports"
	OwnersBeginMark  = "# >>> generated by gragas gen from gate/shared.yaml: the owners' own calls"
	OwnersEndMark    = "# <<< generated by gragas gen: the owners' own calls"
)

// The markers of the instruction block in AGENTS.md.
const (
	AgentsBeginMark = "<!-- >>> generated by gragas gen from gate/shared.yaml: edit that, not this block -->"
	AgentsEndMark   = "<!-- <<< generated by gragas gen -->"
)

