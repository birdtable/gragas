// The markers of the generated block in the lint file. Everything between
// them is the table's; everything outside them is written by hand.
const (
	BeginMark = "# >>> generated by gragas gen from layers.yaml: edit that, not this block"
	EndMark   = "# <<< generated by gragas gen"
)

// indent is the depth of a depguard rule in the lint file: under
// linters.settings.depguard.rules.
const indent = "        "

// ErrNoBlock is a lint file with no generated block, or a broken one.
var ErrNoBlock = errors.New("no generated block")

// Lint is the lint file current with the generated block written from t.
func (t *Table) Lint(current []byte) ([]byte, error) {
	lines := strings.SplitAfter(string(current), "\n")
	begin, end := -1, -1
	for i, l := range lines {
		switch strings.TrimSpace(l) {
		case BeginMark:
			if begin >= 0 {
				return nil, fmt.Errorf("%s: %w: the begin marker is there twice", t.LintFile, ErrNoBlock)
			}
			begin = i
		case EndMark:
			if end >= 0 {
				return nil, fmt.Errorf("%s: %w: the end marker is there twice", t.LintFile, ErrNoBlock)
			}
			end = i
		}
	}
	if begin < 0 || end < begin {
		return nil, fmt.Errorf("%s: %w between %q and %q", t.LintFile, ErrNoBlock, BeginMark, EndMark)
	}
	var b bytes.Buffer
	b.WriteString(strings.Join(lines[:begin+1], ""))
	b.WriteString(t.rows())
	b.WriteString(strings.Join(lines[end:], ""))
	all, err := t.withClock(strings.SplitAfter(b.String(), "\n"))
	if err != nil {
		return nil, err
	}
	if all, err = t.withPrograms(all); err != nil {
		return nil, err
	}
	for _, b := range []struct{ what, begin, end, rows string }{
		{"shared calls", CallsBeginMark, CallsEndMark, t.Shared.callRows()},
		{"shared imports", ImportsBeginMark, ImportsEndMark, t.Shared.importRows()},
		{"shared owners", OwnersBeginMark, OwnersEndMark, t.Shared.ownerRows()},
	} {
		if all, err = t.withBlock(all, b.what, b.begin, b.end, b.rows); err != nil {
			return nil, err
		}
	}
	return []byte(strings.Join(all, "")), nil
}

// rows is the generated depguard rules: one per package for its imports of
// the module, one per pure package for the effect packages, one keeping the
// stand-ins in tests, and one per library for its owner.
func (t *Table) rows() string {
	w := &block{}
	w.line("# One row per package, from its layer: it may import its own package,")
	w.line("# what its row may, and in tests the stand-ins (arch.layers.1, .10).")
	for _, r := range t.Rows {
		for _, pkg := range t.Folders(r) {
			t.packageRow(w, r, pkg)
		}
	}
	t.contextRows(w)
	w.line("# A pure package's non-test files take only the standard packages its")
	w.line("# row lists, each exactly, and no library but a pure one (arch.ports.1).")
	for _, r := range t.Rows {
		if r.Kind != KindPure {
			continue
		}
		for _, pkg := range t.Folders(r) {
			t.pureRow(w, r, pkg)
		}
	}
	w.line("# A stand-in is imported from _test.go files only (arch.layers.10).")
	w.line("stand-ins:")
	w.line("  files: [\"$all\", \"!$test\"]")
	w.line("  deny:")
	for _, s := range t.StandIns() {
		w.line("    - pkg: " + t.Module + "/" + s)
		w.line("      desc: " + quote("arch.layers.10: "+s+" is a stand-in, imported from _test.go files only"))
	}
	w.line("# Each library is imported by its one owner (arch.ports.6); test-only")
	w.line("# packages are exempt.")
	for _, e := range t.External {
		t.ownerRow(w, e)
		t.banRows(w, e)
	}
	return w.String()
}

// contextRows is one rule per context, so the independence of the contexts
// is a rule of its own and not only what each package's row leaves out: a
// context refuses the other contexts (arch.ports.8).
func (t *Table) contextRows(w *block) {
	if len(t.Contexts.Names) == 0 {
		return
	}
	w.line("# The contexts refuse one another, each rule naming the others (arch.ports.8).")
	all := t.ContextPackages()
	for _, name := range t.Contexts.Names {
		mine := ContextPackage(name)
		w.line("context-" + name + ":")
		w.line("  files: [" + quote("**/"+mine+"/**") + "]")
		w.line("  deny:")
		for _, other := range all {
			if other == mine {
				continue
			}
			w.line("    - pkg: " + t.Module + "/" + other)
			w.line("      desc: " + quote(t.Contexts.Why))
		}
	}
}

func (t *Table) packageRow(w *block, r Row, pkg string) {
	allow := []string{pkg}
	allow = append(allow, r.May...)
	allow = append(allow, t.StandIns()...)
	for i, a := range allow {
		allow[i] = allowPath(t, a)
	}
	slices.Sort(allow)
	allow = slices.Compact(allow)
	w.line("layer-" + slug(pkg) + ":")
	w.line("  list-mode: lax")
	w.line("  files: [" + t.folder(pkg) + "]")
	w.line("  deny:")
	w.line("    - pkg: " + t.Module)
	w.line("      desc: " + quote(r.Why))
	w.line("  allow:")
	for _, a := range allow {
		w.line("    - " + t.Module + "/" + a)
	}
}

func (t *Table) pureRow(w *block, r Row, pkg string) {
	w.line("pure-" + slug(pkg) + ":")
	w.line("  list-mode: strict")
	w.line("  files: [" + t.folder(pkg) + ", \"!$test\"]")
	w.line("  allow:")
	for _, s := range r.Std {
		w.line("    - " + s + "$")
	}
	w.line("    - " + t.Module)
	for _, e := range t.External {
		if e.Pure && e.Owner == pkg {
			w.line("    - " + e.Path)
		}
	}
	w.line("  deny:")
	for _, e := range t.Effects {
		w.line("    - pkg: " + e)
		w.line("      desc: " + quote(t.EffectsWhy))
	}
}

func (t *Table) ownerRow(w *block, e External) {
	files := []string{"$all"}
	if e.Owner != "" {
		files = append(files, "!**/"+e.Owner+"/*.go")
	}
	for _, a := range e.Also {
		files = append(files, a.Globs()...)
	}
	for _, w := range e.Within {
		files = append(files, "!**/"+Folder(w)+"/**/*.go")
	}
	for _, r := range t.Rows {
		if r.Kind == KindTests {
			for _, pkg := range r.Packages {
				files = append(files, "!**/"+pkg+"/*.go")
			}
		}
	}
	why := e.Why
	if why == "" {
		why = "arch.ports.6: " + e.Path + " is imported by " + e.Owner + " only"
	}
	// depguard matches a deny by string prefix, and the table by path (the
	// path, or below it at a slash): a bare row for go-console/ui would hold
	// go-console/uitest too. The package itself and the packages below it.
	below := t.sparingBelow(e, files)
	if len(below) == len(files) {
		ownerRule(w, "own-"+slug(e.Path), files, why, e.Path+"$", e.Path+"/")
		return
	}
	// A row below this one holds its own list, and its owners may import the
	// packages below it, not this package: two rules, so the owners spared
	// below are spared the deny of the packages below alone (gragas#1672).
	ownerRule(w, "own-"+slug(e.Path), files, why, e.Path+"$")
	ownerRule(w, "own-"+slug(e.Path)+"-below", below, why, e.Path+"/")
}

// ownerRule is one depguard rule, name, that denies pkgs to every file but those files names.
func ownerRule(w *block, name string, files []string, why string, pkgs ...string) {
	quoted := make([]string, len(files))
	for i, f := range files {
		quoted[i] = quote(f)
	}
	w.line(name + ":")
	w.line("  files: [" + strings.Join(quoted, ", ") + "]")
	w.line("  deny:")
	for _, pkg := range pkgs {
		w.line("    - pkg: " + pkg)
		w.line("      desc: " + quote(why))
	}
}

// sparingBelow is files and the owners (and the `also` owners) of the rows whose path lies below
// e's, which each hold their own list.
func (t *Table) sparingBelow(e External, files []string) []string {
	out := slices.Clone(files)
	for _, o := range t.External {
		if !strings.HasPrefix(o.Path, e.Path+"/") {
			continue
		}
		globs := []string{"!**/" + o.Owner + "/*.go"}
		for _, a := range o.Also {
			globs = append(globs, a.Globs()...)
		}
		for _, g := range globs {
			if !slices.Contains(out, g) {
				out = append(out, g)
			}
		}
	}
	return out
}

// folder is the file globs of pkg's rows: its whole folder, so a new
// package below it is held by its row until the table gives it one, less the
// folders of the packages below it that have rows of their own. The tests
// package at internal/ itself holds its own files only.
func (t *Table) folder(pkg string) string {
	if pkg == "internal" {
		return quote("**/internal/*.go")
	}
	globs := []string{quote("**/" + pkg + "/**")}
	for _, r := range t.Rows {
		for _, q := range t.Folders(r) {
			if strings.HasPrefix(q, pkg+"/") {
				globs = append(globs, quote("!**/"+q+"/**"))
			}
		}
	}
	return strings.Join(globs, ", ")
}

// block is lines at the depth of a depguard rule.
type block struct{ b strings.Builder }

func (w *block) line(s string) { w.b.WriteString(indent + s + "\n") }

func (w *block) String() string { return w.b.String() }

// slug is a path as a rule name: internal/ dropped, a library's host
// dropped, every / and . a dash.
func slug(p string) string {
	if p != "internal" {
		p = strings.TrimPrefix(p, "internal/")
	}
	if first, rest, ok := strings.Cut(p, "/"); ok && strings.Contains(first, ".") {
		p = rest
	}
	return strings.NewReplacer("/", "-", ".", "-").Replace(p)
}

// quote is s as a double-quoted YAML scalar.
func quote(s string) string {
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(s) + `"`
}

// programsDoc is the document's section on the outside programs.
func (t *Table) programsDoc(w *doc) {
	w.add("## The outside programs", "", "Each outside program is started from one adapter package, by the absolute path its setting names, checked, with a fixed argv (arch.ports.6, cli.process.1). "+
		"gosec's G204 sees a variable path there, and the ban of exec.Command and exec.CommandContext holds everywhere a test or a project's own row does not spare, so a generated block in `"+t.LintFile+"` spares the non-test files of these adapters from both, and of no other package. "+
		"A program joins this table in the pull request that builds its adapter.", "", "| Program | Adapter |", "|---|---|")
	for _, pr := range t.Programs {
		w.add(fmt.Sprintf("| `%s` | `%s` |", pr.Name, pr.Adapter))
	}
	if len(t.Programs) == 0 {
		w.add("| none yet | |")
	}
	w.add("")
}

// Doc is the layer document, written from t.
func (t *Table) Doc() string {
	w := &doc{}
	w.add("<!-- generated by gragas gen from "+File+"; edit that, not this file -->", "# Layers", "", t.About, "")
	w.add("| Layer | Kind | Packages | Holds | May import of gragas |", "|---|---|---|---|---|")
	for _, r := range t.Rows {
		may := "nothing"
		if len(r.May) > 0 {
			may = codes(r.May)
		}
		w.add(fmt.Sprintf("| %s | %s | %s | %s | %s |", r.Layer, r.Kind, t.packageCell(r), cell(r.Holds), may))
	}
	w.add("", "Every package may also import its own package, and its tests the stand-ins. A test obeys its package's row (arch.layers.10). "+
		"A package marked planned does not exist yet: it joins its row in the pull request that creates it, and the rows already hold it to this table.", "")
	w.add("## Where the template puts each layer", "")
	for _, r := range t.Rows {
		w.add(r.templateLine())
	}
	w.add("", "## The contexts", "", t.Contexts.Why+" The contexts are "+codes(t.ContextPackages())+". Each has a rule of its own in `"+t.LintFile+"` that refuses the other eight, beside what its layer's row leaves out.", "")
	w.add("## The explorer's modules", "", t.Explorer.Why+" The same table is written as the boundary configuration `"+t.EslintFile+"`, which explorer/eslint.config.js reads.", "", "| Module | Folder | May import |", "|---|---|---|")
	for _, m := range t.Explorer.Modules {
		may := "nothing"
		if len(m.May) > 0 {
			may = codes(m.May)
		}
		w.add(fmt.Sprintf("| `%s` | `%s` | %s |", m.Name, m.Path, may))
	}
	w.add("", "## What only an edge or an adapter imports", "", t.EffectsWhy+": "+codes(t.Effects)+". A trailing `$` matches the path exactly. A pure package refuses these calls too, in its non-test files; a test and the host layer call them with std: "+codes(t.EffectCalls)+".", "")
	w.add("## Each library and the one package that imports it", "", "| Library | Imported by |", "|---|---|")
	for _, e := range t.External {
		by := codes([]string{e.Owner})
		for _, a := range e.Also {
			by += ", and " + codes([]string{a.Owner}) + alsoWhy(a)
		}
		switch {
		case e.Owner == "":
			by = "nothing: " + e.Why
		case e.Pure:
			by += ", a pure library"
		}
		w.add(fmt.Sprintf("| `%s` | %s |", e.Path, by))
	}
	w.add("", "## The ports", "", "| Port | Subject | Adapter |", "|---|---|---|")
	for _, p := range t.Ports.List {
		subject := p.Subject
		if p.Why != "" {
			subject += "; " + p.Why
		}
		w.add(fmt.Sprintf("| `%s` | %s | `%s` |", p.Name, cell(subject), p.Adapter))
	}
	w.add("", fmt.Sprintf("`%s` fills every port in memory. The port package's other interfaces are the values a port hands back: %s.", t.Ports.Fake, codes(t.Ports.Carries)), "")
	t.programsDoc(w)
	w.add("## Platform words", "", "No non-test file of a pure package starts a string with "+codes(t.Platform.Roots)+" in any case, names "+codes(t.Platform.Tools)+", or names a system folder below a home, "+codes(t.Platform.Homes)+"; no port and no fake names "+codes(t.Platform.Names)+" (arch.ports.4, arch.ports.5, arch.ports.17). There is no exception list: the fix for a finding is a port.", "")
	w.add("## Source words", "", "No Go string and no name in "+codes(t.Source.Scope)+" is a rule id (shape `"+t.Source.RuleID+"`), names "+codes(t.Source.Tools)+" or names the config formats "+codes(t.Source.Formats)+": rules and tools are data in adapters, and host/tool runs them (arch.ports.2). No package is named "+codes(t.Source.Refused)+" (arch.structure.7), the files of layer `"+t.Source.LimitLayer+"` stay under "+fmt.Sprint(t.Source.LimitLines)+" lines, and init functions outside main number at most "+fmt.Sprint(t.Source.Inits)+", a count that only falls.", "")
	w.add("## How the table is held", "",
		"`task gen` runs `gragas-dev layers`, which writes this file, the block of depguard rows in `"+t.LintFile+"` and `"+t.EslintFile+"` from `"+File+"`; "+
			"`task generated-files` runs it with `--check` and fails when any of them differs. "+
			"`internal/layers_test.go` holds the tree to the same table with `go list`: every package in one row, every import of a non-test file "+
			"and of a test on an edge its row allows, each library imported by its owner alone, the layout of go.layout.1, and the ports.")
	return strings.Join(w.l, "\n") + "\n"
}

type doc struct{ l []string }

func (w *doc) add(s ...string) { w.l = append(w.l, s...) }

// codes is each of s in backticks, joined by commas.
func codes(s []string) string {
	out := make([]string, len(s))
	for i, x := range s {
		out[i] = "`" + x + "`"
	}
	return strings.Join(out, ", ")
}

// cell is s safe in one table cell.
func cell(s string) string { return strings.ReplaceAll(s, "|", `\|`) }

// Eslint is the explorer's boundary configuration for the ESLint boundaries
// plugin, written from t's explorer table: one element per module, and for
// each module the elements it may import; every other import is refused. It
// is read by explorer/eslint.config.js. A module named
// x/* stands for each folder below x, one element that captures the folder's
// name, so two such folders do not import one another.
func (t *Table) Eslint() string {
	typeOf := func(name string) string { return strings.TrimSuffix(name, "/*") }
	var b strings.Builder
	b.WriteString("{\n")
	b.WriteString("  \"generated_by\": \"gragas-dev layers from " + File + ": edit that, not this file\",\n")
	b.WriteString("  \"why\": " + jsonString(t.Explorer.Why) + ",\n")
	b.WriteString("  \"default\": \"disallow\",\n")
	b.WriteString("  \"elements\": [\n")
	for i, m := range t.Explorer.Modules {
		b.WriteString("    {\"type\": " + jsonString(typeOf(m.Name)) + ", \"pattern\": " + jsonString(m.Path))
		if strings.HasSuffix(m.Name, "/*") {
			b.WriteString(", \"capture\": [\"folder\"]")
		}
		b.WriteString("}" + comma(i, len(t.Explorer.Modules)) + "\n")
	}
	b.WriteString("  ],\n  \"rules\": [\n")
	for i, m := range t.Explorer.Modules {
		allow := make([]string, len(m.May))
		for j, a := range m.May {
			allow[j] = jsonString(typeOf(a))
		}
		b.WriteString("    {\"from\": " + jsonString(typeOf(m.Name)) + ", \"allow\": [" + strings.Join(allow, ", ") + "]}" + comma(i, len(t.Explorer.Modules)) + "\n")
	}
	b.WriteString("  ]\n}\n")
	return b.String()
}

func comma(i, n int) string {
	if i < n-1 {
		return ","
	}
	return ""
}

// jsonString is s as a JSON string: the table's names are plain ASCII, so
// the quote and the backslash are the only characters to escape.
func jsonString(s string) string {
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`, "\n", `\n`).Replace(s) + `"`
}

// packageCell is the packages of r for the table: those that exist, then the
// planned ones, marked, with the milestone that creates each.
func (t *Table) packageCell(r Row) string {
	var parts []string
	if len(r.Packages) > 0 {
		parts = append(parts, codes(r.Packages))
	}
	if len(r.Patterns) > 0 {
		parts = append(parts, "every package below "+codes(r.Patterns))
		if len(r.Carves) > 0 {
			parts = append(parts, "less "+codes(r.Carves)+", which their own rows hold")
		}
	}
	for _, pl := range t.Planned {
		if pl.Layer == r.Layer {
			parts = append(parts, "planned "+pl.Created+": "+codes(pl.Packages))
		}
	}
	if len(parts) == 0 {
		return "none"
	}
	return strings.Join(parts, "; ")
}

// The markers of the second generated block in the lint file: the one
// exclusion that lets the Clock adapter's package call time.Now, the only
// place that does (arch.ports.1). The ban itself is written by hand in the
// forbidigo list; the file is refused when one marker is there without the
// other, and a file with neither has no clock exclusion.
const (
	ClockBeginMark = "# >>> generated by gragas gen from layers.yaml: the Clock adapter's exclusion"
	ClockEndMark   = "# <<< generated by gragas gen: the Clock adapter's exclusion"
)

// ClockMessage is the start of the forbidigo message that bans time.Now; the
// exclusion matches it.
const ClockMessage = "arch.ports.1: only the Clock adapter reads the clock"

// ClockAdapter is the package that fills the Clock port, or "".
func (t *Table) ClockAdapter() string {
	for _, p := range t.Ports.List {
		if p.Name == "Clock" {
			return p.Adapter
		}
	}
	return ""
}

// clockRows is the exclusion rule of the Clock adapter's package, at the
// depth of an item of exclusions.rules.
func (t *Table) clockRows() string {
	pkg := t.ClockAdapter()
	if pkg == "" {
		return ""
	}
	return exclusionPad + "# Only the Clock adapter's package reads the clock; its tests are held too.\n" +
		exclusionPad + "- path: " + yamlSingle(PackageFiles(pkg)) + "\n" +
		exclusionPad + "  linters: [forbidigo]\n" +
		exclusionPad + "  text: " + quote(regexpEscape(ClockMessage)) + "\n"
}

// exclusionPad is the depth of an item of exclusions.rules.
const exclusionPad = "      "

// PackageFiles is the exclusion path that matches the Go files of pkg and
// of no folder below it.
func PackageFiles(pkg string) string { return "(^|/)" + regexpEscape(pkg) + "/[^/]+\\.go$" }

// The markers of the third generated block in the lint file: the G204
// exclusion of each package that starts an outside program, the only places
// gosec's G204 is spared (cli.process.1, arch.ports.6). The program's path is
// a setting, so G204 sees a variable there; the adapter checks the path and
// runs a fixed argv. A file with neither marker has no program exclusion, and
// one marker without the other is refused.
const (
	ProgramsBeginMark = "# >>> generated by gragas gen from layers.yaml: the program adapters' exclusion"
	ProgramsEndMark   = "# <<< generated by gragas gen: the program adapters' exclusion"
)

// The parts of a program adapter's exclusions beside its path: gosec's G204
// is spared, and forbidigo's ban of exec.Command and exec.CommandContext
// (cli.process.1).
const (
	ProgramLinter = "gosec"
	ProgramText   = "G204:"
	ExecLinter    = "forbidigo"
	ExecText      = "cli\\.process\\.1: a program starts through the runner"
)

// NonTestFiles is the exclusion path that matches the Go files of pkg that
// are not tests, and of no folder below it. It is anchored at the start, as
// the lint run gives paths from the module root, so a folder elsewhere that
// ends in the same names is not spared. The lint config refuses path and
// path-except in one rule, and Go's expressions have no lookahead, so the
// name's stem is spelt out: shorter than "_test", or ending in five
// characters that are not "_test".
func NonTestFiles(pkg string) string {
	return "^" + regexpEscape(pkg) + "/([^/]{0,4}|[^/]*([^/_][^/]{4}|_[^/t][^/]{3}|_t[^/e][^/]{2}|_te[^/s][^/]|_tes[^/t]))\\.go$"
}

// programRows is a G204 and an exec.Command exclusion per program adapter, at the depth of an
// item of exclusions.rules.
func (t *Table) programRows() string {
	adapters := t.ProgramAdapters()
	if len(adapters) == 0 {
		return ""
	}
	var b strings.Builder
	b.WriteString(exclusionPad + "# Only an outside program's adapter starts it, by the checked path its\n")
	b.WriteString(exclusionPad + "# setting names; its non-test files alone are spared G204 and the ban of exec.Command.\n")
	for _, pkg := range adapters {
		var names []string
		for _, pr := range t.Programs {
			if pr.Adapter == pkg {
				names = append(names, pr.Name)
			}
		}
		b.WriteString(exclusionPad + "# the adapter of " + strings.Join(names, ", ") + "\n")
		b.WriteString(exclusionPad + "- path: " + yamlSingle(NonTestFiles(pkg)) + "\n")
		b.WriteString(exclusionPad + "  linters: [" + ProgramLinter + "]\n")
		b.WriteString(exclusionPad + "  text: " + quote(ProgramText) + "\n")
		b.WriteString(exclusionPad + "- path: " + yamlSingle(NonTestFiles(pkg)) + "\n")
		b.WriteString(exclusionPad + "  linters: [" + ExecLinter + "]\n")
		b.WriteString(exclusionPad + "  text: " + quote(ExecText) + "\n")
	}
	return b.String()
}

func regexpEscape(s string) string { return regexp.QuoteMeta(s) }

func yamlSingle(s string) string { return "'" + s + "'" }

// withClock is lines with the Clock block, when the file has one, rewritten.
func (t *Table) withClock(lines []string) ([]string, error) {
	return t.withBlock(lines, "clock", ClockBeginMark, ClockEndMark, t.clockRows())
}

// withPrograms is lines with the program adapters' block, when the file has
// one, rewritten.
func (t *Table) withPrograms(lines []string) ([]string, error) {
	return t.withBlock(lines, "programs", ProgramsBeginMark, ProgramsEndMark, t.programRows())
}

// withBlock is lines with what is between the markers begin and end
// replaced by rows. A file with neither marker is returned as it is.
func (t *Table) withBlock(lines []string, what, beginMark, endMark, rows string) ([]string, error) {
	begin, end := -1, -1
	for i, l := range lines {
		switch strings.TrimSpace(l) {
		case beginMark:
			if begin >= 0 {
				return nil, fmt.Errorf("%s: %w: the %s begin marker is there twice", t.LintFile, ErrNoBlock, what)
			}
			begin = i
		case endMark:
			if end >= 0 {
				return nil, fmt.Errorf("%s: %w: the %s end marker is there twice", t.LintFile, ErrNoBlock, what)
			}
			end = i
		}
	}
	if begin < 0 && end < 0 {
		return lines, nil
	}
	if begin < 0 || end < begin {
		return nil, fmt.Errorf("%s: %w between %q and %q", t.LintFile, ErrNoBlock, beginMark, endMark)
	}
	out := slices.Clone(lines[:begin+1])
	if rows != "" {
		out = append(out, strings.SplitAfter(rows, "\n")[:strings.Count(rows, "\n")]...)
	}
	return append(out, lines[end:]...), nil
}

// WithTree is t made to write each pattern as one rule for each package of the
// tree below it, as a package the table lists is written, so a package of a
// pattern may import its own package, its row's may and nothing else of the
// pattern: two packages of one pattern do not import each other unless a may
// says so. A package added below the pattern has no rule until the lint file is
// generated again, which gen --check fails on. Without a tree a pattern is one
// rule for its whole folder.
func (t *Table) WithTree(pkgs []string) *Table {
	t.tree = slices.Clone(pkgs)
	slices.Sort(t.tree)
	t.tree = slices.Compact(t.tree)
	return t
}

// Folders are the folders a row's rules are written for: its packages that
// exist, then the ones planned for it, then each pattern: the packages of the
// tree below its folder that no row lists, or, with no tree, the folder, held
// by one rule that reaches every package below it.
func (t *Table) Folders(r Row) []string {
	out := t.AllPackages(r)
	for _, pat := range r.Patterns {
		if t.tree == nil {
			out = append(out, Folder(pat))
			continue
		}
		for _, pkg := range t.tree {
			if Under(pat, pkg) && !t.listed(pkg) {
				out = append(out, pkg)
			}
		}
	}
	return out
}

// listed is whether a row lists pkg, or has it planned.
func (t *Table) listed(pkg string) bool {
	return slices.ContainsFunc(t.Rows, func(r Row) bool { return slices.Contains(t.AllPackages(r), pkg) })
}

// allowPath is a name an allow list holds, as depguard reads it after the
// module: a package exactly (the $), a pattern as the folder and a slash, which
// depguard takes as the start of an import path, so every package below the
// folder. A row's own folder, when the row holds it by a pattern and lists no
// package there, is also every package below.
func allowPath(t *Table, name string) string {
	if IsPattern(name) {
		return Folder(name) + "/"
	}
	for _, r := range t.Rows {
		if slices.Contains(r.Patterns, name+Wildcard) && !slices.Contains(t.AllPackages(r), name) {
			return name + "/"
		}
	}
	return name + "$"
}

// alsoWhy is how the table words why an owner beside the first one has the library.
func alsoWhy(a Also) string {
	narrow := ""
	if len(a.Files) > 0 {
		narrow = " in " + codes(a.Files)
	}
	if a.Until != "" {
		return narrow + " until " + a.Until
	}
	return narrow + " (" + a.Why + ")"
}

// banRows is one rule per path a library replaced: the old path is refused in
// every file, and the message names the path to import instead (supply.intake.1).
func (t *Table) banRows(w *block, e External) {
	for _, old := range e.Replaces {
		w.line("ban-" + slug(old) + ":")
		w.line("  files: [\"$all\"]")
		w.line("  deny:")
		w.line("    - pkg: " + old)
		w.line("      desc: " + quote("supply.intake.1: "+old+" is banned; import "+e.Path+" instead"))
	}
}

// templateLine is the row's bullet in the document: where the template puts
// the layer, what a breach says, and the row's temporary, product or home and
// standard-package notes.
func (r Row) templateLine() string {
	line := fmt.Sprintf("- **%s.** %s. A breach says: %s.", r.Layer, r.Template, r.Why)
	if r.Until != "" {
		line += " Temporary: this row is gone by " + r.Until + "."
	}
	if r.Product != "" {
		line += " Product code: " + strings.TrimRight(r.Product, ".") + "."
	}
	if r.Home != "" {
		line += " Belongs in " + r.Home + "."
	}
	if len(r.Std) > 0 {
		line += " Its standard packages, and no other: " + codes(r.Std) + "."
	}
	return line
}
