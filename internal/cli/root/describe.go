package root

// The documents made from the registry and the command tree: the command
// table (docs/commands.md), the command-tree file (docs/command-tree.json)
// and the table in the README. cmd/gragas-docs writes them (task gen) and
// compares them (task generated-files). Nothing here is written by hand
// (gates.own-rules.3).

import (
	"context"
	"fmt"
	"github.com/birdtable/gragas/internal/cli/kit"
	"reflect"
	"slices"
	"strings"

	"github.com/spf13/cobra"
	"github.com/spf13/pflag"

	coreapi "github.com/birdtable/gragas/internal/core/api"
	"github.com/birdtable/gragas/internal/exit"
	"github.com/birdtable/gragas/internal/model"
	"github.com/birdtable/gragas/internal/rendered"
)

// Paths of the generated documents, from the repository's root.
const (
	CommandsDoc = "docs/commands.md"
	TreeFile    = "docs/command-tree.json"
	ReadmeFile  = "README.md"
)

// The markers around the README's command table. The table between them is
// the generator's; the rest of the README is the owner's.
const (
	ReadmeBegin = "<!-- commands:begin generated by gragas-docs from the command registry (task gen): edit the registry, not this table -->"
	ReadmeEnd   = "<!-- commands:end -->"
)

// asOf is the date the generated command table carries. It moves with the
// registry: the change that edits a row sets it.
const asOf = "2026-11-08"

// Document is one generated file.
type Document struct {
	Path string
	Data []byte
}

// Documents are the generated files, in a fixed order, made from the registry
// and from a command tree built the way a run builds it. readme is the README
// as it stands: only the table between its markers is replaced.
func Documents(ctx context.Context, readme []byte) ([]Document, error) {
	reg := commands()
	tree := (&session{}).newRoot(ctx)
	if bad := reg.TreeProblems(treeNames(tree)); len(bad) > 0 {
		return nil, fmt.Errorf("the command tree and the registry disagree: %s", strings.Join(bad, ", "))
	}
	file, err := treeFile(reg, tree)
	if err != nil {
		return nil, err
	}
	spliced, err := splice(readme, readmeTable(reg))
	if err != nil {
		return nil, err
	}
	return []Document{
		{CommandsDoc, []byte(commandsDoc(reg))},
		{TreeFile, file},
		{ReadmeFile, spliced},
	}, nil
}

// splice replaces what stands between the README's markers by table.
func splice(readme []byte, table string) ([]byte, error) {
	out, err := rendered.Splice(readme, ReadmeBegin, ReadmeEnd, []byte("\n"+table+"\n"))
	if err != nil {
		return nil, fmt.Errorf("%s has no command table between its markers %s: %w", ReadmeFile, ReadmeBegin, err)
	}
	return out, nil
}

// readmeTable is the README's command table: every command, and whether it
// works yet.
func readmeTable(r kit.Registry) string {
	var b strings.Builder
	b.WriteString("| Command | What it does | Works now |\n|---|---|---|\n")
	for _, c := range r.Rows() {
		what := c.Summary
		if len(c.Then) > 0 {
			what += ". Takes " + strings.Join(c.Then, ", ")
		}
		fmt.Fprintf(&b, "| `gragas %s` | %s | %s |\n", c.Name, cell(what), worksNow(c))
	}
	return b.String()
}

// worksNow says in a word whether the command is in this build.
func worksNow(c kit.Command) string {
	switch c.State {
	case kit.Built:
		if len(c.NotYet) > 0 {
			return "yes, except " + strings.Join(c.NotYet, ", ") + " (not yet)"
		}
		return "yes"
	case kit.Legacy:
		return "yes, the old one until M6"
	case kit.NotBuilt:
	}
	return "not yet"
}

// cell makes s safe in a Markdown table cell.
func cell(s string) string { return strings.ReplaceAll(s, "|", "/") }

func endsText(c kit.Command) string {
	if c.OptIn {
		if c.Name == "docs" {
			return "report, and in the accept form a plan"
		}
		return "listing, and in the opt-in form a plan"
	}
	return string(c.Ends)
}

func wordList(ws []model.Word) string {
	s := make([]string, len(ws))
	for i, w := range ws {
		s[i] = string(w)
	}
	return strings.Join(s, ", ")
}

// commandsDoc is docs/commands.md: the full table of the registry.
func commandsDoc(r kit.Registry) string {
	var b strings.Builder
	b.WriteString("<!-- generated by gragas-docs from the command registry (task gen): edit internal/cli/root/registry_data.go, not this file -->\n")
	b.WriteString("---\ntype: reference\nstatus: current\nas-of: " + asOf + "\n---\n\n# Commands\n\n")
	b.WriteString("Every command gragas has decided on, from the one registry the program is built from. ")
	b.WriteString("A command in the tree works now. A command that is not built yet is listed so that nothing in the help or the README promises it. ")
	b.WriteString("Any command can also end usage, busy or not ready.\n\n")
	section := func(title string, keep func(kit.Command) bool) {
		b.WriteString("## " + title + "\n\n")
		b.WriteString("| Command | Context | Ends in | Writes | Closing words | JSON kind |\n|---|---|---|---|---|---|\n")
		n := 0
		for _, c := range r.Rows() {
			if !keep(c) {
				continue
			}
			n++
			writes := strings.Join(c.Writes, ", ")
			if writes == "" {
				writes = "nothing"
			}
			fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s |\n", c.Usage(), c.Context, endsText(c), cell(writes), wordList(c.Exits), c.JSONKind)
		}
		if n == 0 {
			b.WriteString("| none |  |  |  |  |  |\n")
		}
		b.WriteString("\n")
	}
	section("In the tree", func(c kit.Command) bool { return c.State != kit.NotBuilt })
	section("Not built yet", func(c kit.Command) bool { return c.State == kit.NotBuilt })
	if words := r.NotBuiltWords(); len(words) > 0 {
		b.WriteString("Not built, as typed: " + strings.Join(words, ", ") + ".\n\n")
	}
	b.WriteString("Context: R a rulebook's repository, P a project, B both, A anywhere.\n")
	return b.String()
}

// treeFile is the command-tree file: the commands in the tree with their
// flags, type and default, positionals, exit codes and the JSON fields of the
// answer, and the not-built list. A change to any of it is a change to the
// program's surface and shows in this file's diff (cli.output.4).
func treeFile(r kit.Registry, tree *cobra.Command) ([]byte, error) {
	doc := coreapi.CommandTree{Schema: 1, GeneratedBy: "gragas-docs", JSONFields: jsonFields(reflect.TypeFor[coreapi.Result]()),
		Global: flagsOf(tree.PersistentFlags())}
	for _, c := range tree.Commands() {
		if c.Name() == "help" || c.Name() == "completion" {
			continue
		}
		row, _ := r.Find(c.Name())
		doc.Commands = append(doc.Commands, treeCommands(c, row)...)
	}
	slices.SortFunc(doc.Commands, func(a, b coreapi.TreeCommand) int { return strings.Compare(a.Path, b.Path) })
	doc.NotBuilt = r.NotBuiltWords()
	return renderJSON(doc)
}

// positionals are the arguments a command takes, as its Use line writes them
// after its name.
func positionals(c *cobra.Command) string {
	_, rest, _ := strings.Cut(c.Use, " ")
	return strings.TrimSpace(rest)
}

func flagsOf(fs *pflag.FlagSet) []coreapi.TreeFlag {
	var out []coreapi.TreeFlag
	fs.VisitAll(func(f *pflag.Flag) {
		out = append(out, coreapi.TreeFlag{Name: f.Name, Shorthand: f.Shorthand, Type: f.Value.Type(), Default: f.DefValue, Usage: f.Usage})
	})
	slices.SortFunc(out, func(a, b coreapi.TreeFlag) int { return strings.Compare(a.Name, b.Name) })
	return out
}

// exitsOf are the codes a row's closing words map to, and the three any
// command can end on.
func exitsOf(c kit.Command) []coreapi.TreeExit {
	ws := slices.Clone(c.Exits)
	for _, w := range []model.Word{model.Usage, model.Busy, model.NotReady} {
		if !slices.Contains(ws, w) {
			ws = append(ws, w)
		}
	}
	var out []coreapi.TreeExit
	for _, w := range ws {
		code, _ := exit.Code(w)
		out = append(out, coreapi.TreeExit{Word: string(w), Code: code})
	}
	slices.SortStableFunc(out, func(a, b coreapi.TreeExit) int { return a.Code - b.Code })
	return out
}

// jsonFields are the top-level fields of the answer a run gives under --json,
// from the result type's own tags.
func jsonFields(t reflect.Type) []string {
	var out []string
	for f := range t.Fields() {
		name, _, _ := strings.Cut(f.Tag.Get("json"), ",")
		if name != "" && name != "-" {
			out = append(out, name)
		}
	}
	return out
}

// treeCommands is c and the commands under it, each with its row's state,
// exits and JSON kind: `cache list` is a line of the file beside `cache`.
func treeCommands(c *cobra.Command, row kit.Command) []coreapi.TreeCommand {
	out := []coreapi.TreeCommand{{
		Path: c.CommandPath(), State: string(row.State), Positionals: positionals(c), Flags: flagsOf(c.NonInheritedFlags()),
		Exits: exitsOf(row), JSONKind: row.JSONKind,
	}}
	for _, sub := range c.Commands() {
		if sub.Name() != "help" && sub.Name() != "completion" {
			out = append(out, treeCommands(sub, row)...)
		}
	}
	return out
}
