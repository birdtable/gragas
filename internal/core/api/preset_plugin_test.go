// TestThePresetRequestHoldsTheToolVersionTheMarkAndTheInputs: the request
// names the lower bound of the manifest's tool_versions, the one mark even for
// a copy the project may take, and each input read from presets/<tool>/; a range with
// no lower bound is refused and a missing input is ErrSettingsInputMissing.
// Risk: a plugin asked for a version its range leaves out, or for an input
// read from elsewhere.
func TestThePresetRequestHoldsTheToolVersionTheMarkAndTheInputs(t *testing.T) {
	t.Parallel()
	rules := strings.Replace(presetRulesActive(), "target: config", "target: source", 1)
	got, err := presetCaptured(t, rules, func(p *porttest.StandinPlugin) { p.Facts.Extends = false })
	if err != nil {
		t.Fatal(err)
	}
	if got.ToolVersion != "1.0.0" {
		t.Errorf("ToolVersion = %q, want the lower bound 1.0.0", got.ToolVersion)
	}
	if got.Mark == nil || *got.Mark != "Generated by gragas from the rulebook. Regenerate it, never change it by hand." {
		t.Errorf("Mark = %v, want the one mark, whatever extends says", got.Mark)
	}
	if len(got.Inputs) != 1 || got.Inputs[0].Path != "in.txt" || got.Inputs[0].Data.Text == nil || *got.Inputs[0].Data.Text != "an input\n" {
		t.Errorf("Inputs = %+v, want in.txt as the folder holds it", got.Inputs)
	}
	if _, err := presetCaptured(t, rules, func(p *porttest.StandinPlugin) { p.Facts.ToolVersions = "<2.0.0" }); err == nil || !strings.Contains(err.Error(), "no lower bound") {
		t.Errorf("a range with no lower bound gave %v, want it refused", err)
	}
	if _, err := presetCaptured(t, rules, func(p *porttest.StandinPlugin) { p.Facts.Preset.Inputs = []string{"gone.txt"} }); !errors.Is(err, coreapi.ErrSettingsInputMissing) {
		t.Errorf("a missing input gave %v, want ErrSettingsInputMissing", err)
	}
}

// TestACopyOnceFileIsTheProjectsAndAnExtendingOneIsWrittenAgain
// (generate.go:238, copyOnce: !ad.Extends): where the manifest does not extend,
// an edited file survives a run and the check names it as the project's and
// does not compare it; where it does, the run writes it again. Risk: a project's own copy overwritten, or an
// extended preset left to drift.
func TestACopyOnceFileIsTheProjectsAndAnExtendingOneIsWrittenAgain(t *testing.T) {
	t.Parallel()
	for name, extends := range map[string]bool{"a copy-once file is the projects": false, "an extending file is written again": true} {
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			const mine = "# mine\n"
			rules := strings.Replace(presetRulesActive(), "target: config", "target: source", 1)
			w, root := presetBook(t, rules, map[string]string{pluginPresetFile: mine})
			p := porttest.NewStandinPlugin()
			p.Facts.Tool = "lint-a"
			p.Facts.Extends = extends
			p.Facts.Preset = &plugin.ManifestPreset{Path: "standin.conf", Mark: true}
			w.PluginsOf().Install(string(root), model.PluginRef{Name: "standin", Version: "1.0.0"}, p)
			ctx := context.Background()
			c, _, err := coreapi.Preset(ctx, w.Ports(), changeAsk(root, "gragas preset"))
			if err != nil {
				t.Fatal(err)
			}
			c.Apply(ctx, "")
			got := read(t, w, root, pluginPresetFile)
			rep, err := coreapi.PresetCheck(ctx, w.Ports(), root)
			if err != nil {
				t.Fatalf("check %+v, %v", rep, err)
			}
			if !extends && (got != mine || len(rep.Files) != 0 || !slices.Equal(rep.Owned, []string{pluginPresetFile})) {
				t.Errorf("the copy a project owns was written over (%q) or the check compared it (%+v)", got, rep)
			}
			if extends && len(rep.Files) != 1 {
				t.Errorf("check %+v, want the extending preset's file compared", rep)
			}
			if extends && got == mine {
				t.Errorf("the file of an extending preset was left as the project's")
			}
		})
	}
}

// TestARuleChangeWritesThePluginsPreset: a bind of a tool a plugin serves
// shows and writes the plugin's file, at the path the manifest names. Risk: a
