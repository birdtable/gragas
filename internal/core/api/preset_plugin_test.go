// presetPluginWorld is the preset world with the stand-in installed for
// lint-a, whose one binding is at the source target the stand-in serves. The
// manifest names standin.conf, the file the stand-in answers.
func presetPluginWorld(t *testing.T, extends bool) (*porttest.World, model.Root, *porttest.StandinPlugin) {
	t.Helper()
	rules := strings.Replace(presetRulesActive(), "target: config", "target: source", 1)
	w, root := presetBook(t, rules, nil)
	p := porttest.NewStandinPlugin()
	p.Facts.Tool = "lint-a"
	p.Facts.Extends = extends
	p.Facts.Preset = &plugin.ManifestPreset{Path: "standin.conf", Mark: true}
	w.PluginsOf().Install(string(root), model.PluginRef{Name: "standin", Version: "1.0.0"}, p)
	return w, root, p
}

const pluginPresetFile = "presets/lint-a/standin.conf"

// TestAToolAPluginServesIsWrittenByItsPreset: the
// file is the plugin's answer at presets/<tool>/<path>, not the adapter's, with
// the mark the manifest asks for, the one mark whatever extends says; the
// plugin is opened and closed once.
// Risk: the adapter's file written beside, or instead of, the plugin's.
func TestAToolAPluginServesIsWrittenByItsPreset(t *testing.T) {
	t.Parallel()
	w, root, p := presetPluginWorld(t, false)
	ctx := context.Background()
	c, ref, err := coreapi.Preset(ctx, w.Ports(), changeAsk(root, "gragas preset"))
	if err != nil || ref != nil {
		t.Fatal(ref, err)
	}
	if out := c.Apply(ctx, ""); out.Word != model.Done {
		t.Fatalf("apply ended %q (%v)", out.Word, out.Cause)
	}
	want := "# Generated by gragas from the rulebook. Regenerate it, never change it by hand.\nwrap-errors error\n"
	if got := read(t, w, root, pluginPresetFile); got != want {
		t.Errorf("%s =\n%q\nwant\n%q", pluginPresetFile, got, want)
	}
	if opened, closed := p.Opened(); opened == 0 || opened != closed {
		t.Errorf("the plugin was opened %d and closed %d times, want each plugin closed", opened, closed)
	}
	rep, err := coreapi.PresetCheck(ctx, w.Ports(), root)
	if err != nil || len(rep.Files) != 1 || rep.Files[0].State != coreapi.PresetSame || rep.Files[0].Path != pluginPresetFile {
		t.Errorf("check = %+v, %v, want the plugin's file the same", rep, err)
	}
}

// TestAPresetAnswerOfAnotherPathWritesNothing: each path that is not the
// manifest's, byte for byte, is an AnswerError at /files/0/path, and nothing
// is written, not the adapter's file either. Risk: a plugin that writes a file
// of its choosing below the rulebook's presets.
func TestAPresetAnswerOfAnotherPathWritesNothing(t *testing.T) {
	t.Parallel()
	for _, path := range []string{"Standin.conf", "./standin.conf", "../standin.conf", "other.conf", "sub/standin.conf", "standin.conf ", ""} {
		t.Run(path, func(t *testing.T) {
			t.Parallel()
			w, root, p := presetPluginWorld(t, true)
			p.OnPreset = func(plugin.PresetRequest) (plugin.PresetResponse, error) {
				return plugin.PresetResponse{Files: []plugin.PresetFile{{Path: path, Text: "x\n"}}}, nil
			}
			_, _, err := coreapi.Preset(context.Background(), w.Ports(), changeAsk(root, "gragas preset"))
			var ae *plugin.AnswerError
			if !errors.As(err, &ae) || ae.Path != "/files/0/path" {
				t.Fatalf("Preset = %v, want an AnswerError at /files/0/path", err)
			}
			for _, f := range []string{pluginPresetFile, presetFile, "presets/lint-a/" + path} {
				if _, err := w.Ports().Tree.Read(root, f); err == nil {
					t.Errorf("%s was written", f)
				}
			}
			if opened, closed := p.Opened(); opened != closed {
				t.Errorf("the plugin was opened %d and closed %d times", opened, closed)
			}
		})
	}
}

