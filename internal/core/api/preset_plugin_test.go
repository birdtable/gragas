// TestAPluginsFileNamedLikeAnotherToolsIsNotThatFile: a plugin of the tool other whose preset path is the file name
// the adapter of lint-a writes makes its own file below presets/other/, and a
// rule change leaves lint-a's file as it was. Risk: the plan keys a preset by its
// path alone, so one tool's bytes are written over another tool's file.
func TestAPluginsFileNamedLikeAnotherToolsIsNotThatFile(t *testing.T) {
	t.Parallel()
	rules := strings.Replace(presetRulesActive(), "strength: may\n    status: proposed", "strength: may\n    status: active", 1)
	w, root := presetBook(t, rules, nil)
	p := porttest.NewStandinPlugin()
	p.Facts.Tool = "other"
	p.Facts.Extends = true
	p.Facts.Preset = &plugin.ManifestPreset{Path: "lint-a.yml", Mark: true}
	p.OnPreset = func(r plugin.PresetRequest) (plugin.PresetResponse, error) {
		text := "OTHER PLUGIN BYTES\n"
		for _, e := range r.Entries {
			text += e.Key + "\n"
		}
		return plugin.PresetResponse{Files: []plugin.PresetFile{{Path: "lint-a.yml", Text: text}}}, nil
	}
	// another ref than the world's own, so lint-a stays served beside it
	w.PluginsOf().Install(string(root), model.PluginRef{Name: "other", Version: "1.0.0"}, p)
	ctx := context.Background()
	apply := func(c *coreapi.Change, ref *model.Refusal, err error) {
		t.Helper()
		if err != nil || ref != nil {
			t.Fatal(ref, err)
		}
		if out := c.Apply(ctx, ""); out.Word != model.Done {
			t.Fatalf("apply ended %q (%v)", out.Word, out.Cause)
		}
	}
	apply(coreapi.Preset(ctx, w.Ports(), changeAsk(root, "gragas preset")))
	adapters := read(t, w, root, presetFile)
	if adapters == "" {
		t.Fatalf("%s was not written by the adapter", presetFile)
	}
	req := model.BindRule{ID: "go.errors.2", Binding: model.Binding{Tool: "other", Target: "source", Key: "log-once", Value: true, Severity: model.SeverityError, Rung: 1, RunPoint: "commit"}}
	apply(coreapi.Bind(ctx, w.Ports(), coreapi.OverlayAsk{ChangeAsk: runTwo(changeAsk(root, "gragas bind go.errors.2"))}, req))
	if got := read(t, w, root, presetFile); got != adapters {
		t.Errorf("lint-a's file was written over:\n%q\nwas\n%q", got, adapters)
	}
	if got := read(t, w, root, "presets/other/lint-a.yml"); !strings.Contains(got, "log-once") {
		t.Errorf("the plugin's own file is %q, want it to hold log-once", got)
	}
}

